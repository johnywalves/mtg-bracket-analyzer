import type { DeckCardEntry, DeckReport, DeckSummary } from "@/lib/types";

// Imagem via endpoint "named" do Scryfall (redireciona pro CDN da carta) —
// só pra preview no mock; o motor real guarda `image_url` já resolvido no
// banco local de cards (ver golden rule 4 do CLAUDE.md).
function card(
  name: string,
  type: DeckCardEntry["type"],
  quantity = 1,
  mana_cost: string | null = null,
): DeckCardEntry {
  return {
    name,
    type,
    quantity,
    mana_cost,
    image_url: `https://api.scryfall.com/cards/named?exact=${encodeURIComponent(name)}&format=image&version=normal`,
  };
}

/** Mesma lógica de backend/mtg_analyzer/data/deck_library.py::slugify. */
export function slugify(name: string): string {
  return name
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

